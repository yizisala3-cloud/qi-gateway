"""Disposable real PostgreSQL: cooldown, snapshots, retries and retention races."""
import json
import os
import tempfile
import unittest
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timedelta, timezone
from pathlib import Path
from uuid import uuid4

try:
    import pgserver
    import psycopg
    STACK_AVAILABLE = True
except ImportError:
    STACK_AVAILABLE = False

from tests.test_migration_pgserver_integration import _ensure_pg_timezone_data

ROOT = Path(__file__).resolve().parents[1]
MIGRATION = ROOT / "supabase/migrations/20261020020000_memory_recall_cooldown_history.sql"

BASE = """create role anon; create role authenticated; create role service_role bypassrls;
create schema extensions;
create extension vector with schema extensions;
grant usage on schema public, extensions to anon, authenticated, service_role;
create table public.memories (
 id integer generated by default as identity primary key, content text, title text,
 tags text[], heat double precision default 50, importance integer default 5,
 created_at timestamptz default now(), last_recalled_at timestamptz,
 recall_count integer default 0, is_active boolean default true,
 verified text default 'verified', continuity_id uuid, continuity_type text default 'moment',
 continuity_schema_version smallint, continuity_data jsonb, source_type text,
 thread_state text default 'standalone', memory_time timestamptz, evidence_start_time timestamptz,
 evidence_end_time timestamptz, source_time timestamptz, time_precision text,
 evidence_time_precision text, recall_scene text, recall_tags text[], recall_embedding extensions.vector
);
"""


@unittest.skipUnless(STACK_AVAILABLE and os.environ.get("QIGATEWAY_PG_MIGRATION_TEST") == "1", "run pytest --db for isolated PostgreSQL")
class RecallPostgresTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        _ensure_pg_timezone_data()
        cls.pgdata = Path(tempfile.mkdtemp(prefix="qigate-recall-"))
        cls.server = pgserver.get_server(cls.pgdata, cleanup_mode="stop")
        cls.uri = cls.server.get_uri()
        cls.conn = psycopg.connect(cls.uri, autocommit=True)
        cls.conn.execute(BASE)
        # Exercise replacement of the actual latest signatures and definitions.
        baseline = (ROOT / "supabase/migrations/20260905010000_rumination_continuity_path.sql").read_text(encoding="utf-8")
        a = baseline.index("drop function if exists public.match_memories(", baseline.index("-- 7. Recall:"))
        b = baseline.index("-- 8. Fast-path write gating", a)
        cls.conn.execute(baseline[a:b])
        cls.conn.execute(MIGRATION.read_text(encoding="utf-8"))

    @classmethod
    def tearDownClass(cls):
        cls.conn.close()
        cls.server.cleanup()

    def setUp(self):
        self.conn.execute("truncate public.memory_recall_history, public.memory_recall_batches, public.memories restart identity")
        self.mid = self.conn.execute("insert into memories(content,title,recall_scene,recall_embedding) values ('聊天测试正文','原始标题','聊天','[1,0,0]') returning id").fetchone()[0]

    def record(self, batch=None, at=None, text="实际注入片段", mid=None, conn=None):
        return (conn or self.conn).execute(
            "select record_memory_recall_batch_v1(%s,%s,%s::jsonb)",
            (batch or uuid4(), at or datetime.now(timezone.utc), json.dumps([{
                "memory_id": mid or self.mid, "title": "历史标题", "continuity_type": "moment", "injection_text": text,
            }], ensure_ascii=False)),
        ).fetchone()[0]

    def keyword_ids(self, cooldown=3600):
        return [row[0] for row in self.conn.execute("select id from search_memories_by_keywords(array['聊天'],50,%s)", (cooldown,))]

    def vector_ids(self, cooldown=3600):
        return [row[0] for row in self.conn.execute("select id from match_memories('[1,0,0]'::extensions.vector,0.5,50,%s)", (cooldown,))]

    def test_both_channels_cooldown_disable_expiry_and_exemptions(self):
        for query in (self.keyword_ids, self.vector_ids):
            self.assertIn(self.mid, query())
        self.record()
        for query in (self.keyword_ids, self.vector_ids):
            self.assertNotIn(self.mid, query())
            self.assertIn(self.mid, query(0))
        for ctype in ("profile", "interaction_rule"):
            self.conn.execute("update memories set continuity_type=%s", (ctype,))
            for query in (self.keyword_ids, self.vector_ids):
                self.assertIn(self.mid, query())
        self.conn.execute("update memories set continuity_type='moment', last_recalled_at=now()-interval '1 hour'")
        for query in (self.keyword_ids, self.vector_ids):
            self.assertIn(self.mid, query())

    def test_original_guards_and_cooldown_before_candidate_limit(self):
        self.conn.execute("insert into memories(content,title,recall_scene,recall_embedding,last_recalled_at) select '聊天','聊天','聊天','[1,0,0]',now() from generate_series(1,60)")
        for query in (self.keyword_ids, self.vector_ids):
            self.assertEqual(query(), [self.mid])
        for change in ("is_active=false", "verified='rejected'", "continuity_type='thread',thread_state='resolved'"):
            self.conn.execute(f"update memories set {change} where id=%s", (self.mid,))
            for query in (self.keyword_ids, self.vector_ids):
                self.assertNotIn(self.mid, query(0))
            self.conn.execute("update memories set is_active=true,verified='verified',continuity_type='moment' where id=%s", (self.mid,))

    def test_repeat_injections_retain_snapshots_and_single_retry_counts_once(self):
        batch = uuid4()
        self.record(batch=batch)
        self.record(batch=batch)
        self.record()
        self.assertEqual(self.conn.execute("select count(*) from memory_recall_history").fetchone()[0], 2)
        self.assertEqual(self.conn.execute("select recall_count from memories").fetchone()[0], 2)
        self.conn.execute("update memories set content='编辑后的正文',title='编辑后的标题'")
        self.assertEqual(self.conn.execute("select title,injection_text from memory_recall_history limit 1").fetchone(), ("历史标题", "实际注入片段"))
        self.conn.execute("delete from memories")
        self.assertEqual(self.conn.execute("select count(*) from memory_recall_history").fetchone()[0], 2)

    def test_retention_concurrency_old_arrivals_and_retry_after_pruning(self):
        old_time = datetime.now(timezone.utc) - timedelta(minutes=5)
        batch = uuid4()
        self.record(batch=batch, at=old_time)
        def writer(index):
            with psycopg.connect(self.uri, autocommit=True) as conn:
                for offset in range(20):
                    self.record(text=f"并发 {index}-{offset}", conn=conn)
        with ThreadPoolExecutor(max_workers=8) as pool:
            list(pool.map(writer, range(8)))
        self.assertEqual(self.conn.execute("select count(*) from memory_recall_history").fetchone()[0], 150)
        self.assertEqual(self.conn.execute("select count(*) from memory_recall_history where batch_id=%s", (batch,)).fetchone()[0], 0)
        self.record(batch=batch, at=old_time)
        self.assertEqual(self.conn.execute("select recall_count from memories").fetchone()[0], 161)
        stamp = self.conn.execute("select last_recalled_at from memories").fetchone()[0]
        self.record(at=old_time)
        self.assertEqual(self.conn.execute("select last_recalled_at from memories").fetchone()[0], stamp)
        self.assertEqual(self.conn.execute("select count(*) from memory_recall_history").fetchone()[0], 150)

    def test_permissions_rerun_preserves_history_and_payload_rejects_atomically(self):
        self.record()
        self.conn.execute(MIGRATION.read_text(encoding="utf-8"))
        self.assertEqual(self.conn.execute("select count(*) from memory_recall_history").fetchone()[0], 1)
        for role in ("anon", "authenticated"):
            self.conn.execute(f"set role {role}")
            try:
                with self.assertRaises(psycopg.errors.InsufficientPrivilege):
                    self.conn.execute("select * from memory_recall_history")
                with self.assertRaises(psycopg.errors.InsufficientPrivilege):
                    self.record()
            finally:
                self.conn.execute("reset role")
        self.conn.execute("set role service_role")
        try:
            self.assertEqual(self.conn.execute("select count(*) from memory_recall_history").fetchone()[0], 1)
            self.record()
        finally:
            self.conn.execute("reset role")
        with self.assertRaises(psycopg.errors.RaiseException):
            self.record(text="x" * 2401)
        self.assertEqual(self.conn.execute("select count(*) from memory_recall_history").fetchone()[0], 2)
