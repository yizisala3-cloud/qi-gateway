class RuminationMigrationOnPostgresTests(unittest.TestCase):
    """Executes the rumination RPCs on a real, disposable database."""

    @classmethod
    def setUpClass(cls):
        if not _STACK_AVAILABLE:
            raise unittest.SkipTest("pgserver + psycopg are not installed")
        if os.environ.get("QIGATEWAY_PG_MIGRATION_TEST") != "1":
            raise unittest.SkipTest(
                "set QIGATEWAY_PG_MIGRATION_TEST=1 to run the real "
                "PostgreSQL migration execution test"
            )
        cls.pgdata = Path(tempfile.mkdtemp(prefix="qigate-rumination-"))
        cls.server = None
        cls.conn = None
        try:
            _ensure_pg_timezone_data()
            cls.server = pgserver.get_server(cls.pgdata, cleanup_mode="stop")
            cls.conn = psycopg.connect(cls.server.get_uri(), autocommit=True)
            cls.conn.execute(BASELINE_SQL)
            cls._apply_history()
            cls._seed()
        except Exception:
            cls.tearDownClass()
            raise

    @classmethod
    def tearDownClass(cls):
        conn = getattr(cls, "conn", None)
        if conn is not None:
            conn.close()
            cls.conn = None
        server = getattr(cls, "server", None)
        if server is not None:
            server.cleanup()
            cls.server = None
        pgdata = getattr(cls, "pgdata", None)
        if pgdata is not None and pgdata.exists():
            shutil.rmtree(pgdata, ignore_errors=True)

    # -- helpers ----------------------------------------------------------

    def _query(self, sql, params=None):
        with self.conn.cursor() as cur:
            cur.execute(sql, params)
            return cur.fetchall()

    def _query_one(self, sql, params=None):
        rows = self._query(sql, params)
        return rows[0][0] if rows else None

    def _query_row(self, sql, params=None):
        rows = self._query(sql, params)
        return tuple(rows[0]) if rows else None

    def _call(self, name, params):
        from psycopg import sql as psql

        parts = []
        values = []
        for value in params.values():
            if isinstance(value, (dict, list)):
                parts.append(psql.SQL("%s::jsonb"))
                values.append(json.dumps(value))
            elif isinstance(value, bool):
                parts.append(psql.SQL("%s::boolean"))
                values.append(value)
            elif isinstance(value, int):
                parts.append(psql.SQL("%s::bigint"))
                values.append(value)
            elif value is None:
                # 无类型 NULL：让 PG 按函数签名解析参数类型。
                parts.append(psql.SQL("%s"))
                values.append(None)
            else:
                parts.append(psql.SQL("%s::text"))
                values.append(str(value))
        query = psql.SQL("select public.{name}({args})").format(
            name=psql.SQL(name),
            args=psql.SQL(", ").join(parts),
        )
        with self.conn.cursor() as cur:
            cur.execute(query, values)
            row = cur.fetchall()[0][0]
        if isinstance(row, str):
            return json.loads(row)
        return row

    @classmethod
    def _apply_history(cls):
        for path in sorted(MIGRATIONS_DIR.glob("*.sql")):
            sql = path.read_text(encoding="utf-8")
            if path.name == PG_TRGM_FILE:
                sql = sql.replace(PG_TRGM_LINE, "-- pg_trgm stubbed (pgserver)")
            cls.conn.execute(sql)

    @classmethod
    def _seed(cls):
        # Multi-statement SQL cannot go through the extended protocol with
        # parameters, so the hashes are inlined as quoted literals.
        cls.conn.execute(
            SEED_SQL
            .replace("__FAST_THREAD_HASH__", _sha256("叶子和栖约好下周三赶海，正在确认天气。"))
            .replace("__RUM_THREAD_HASH__", _sha256("赶海计划当前状态：约定下周三出行，等待天气确认。"))
            .replace("__RUM_THREAD2_HASH__", _sha256("夜间观察计划当前状态：约定观察猎户座，等待晴夜。"))
            .replace("__MOMENT_HASH__", _sha256("叶子和栖把防晒霜叫作贝壳的瞬间。"))
            .replace("__RESOLVED_THREAD_HASH__", _sha256("赶海回顾进程已明确完成：双方顺利赶海并整理收获。"))
        )

    def setUp(self):
        # Every test is order-independent: no leftover live runs, no leftover
        # scheduled-execution rows, and a cursor at a known position.
        self.conn.execute(
            "update public.memory_digest_runs set status = 'failed', "
            "error_code = 'test_cleanup' "
            "where pipeline = 'rumination' and status in ('claimed', 'running')"
        )
        self.conn.execute(
            "delete from public.memory_rumination_scheduled_executions "
            "where assistant_id = %s", (ASSISTANT,),
        )
        self._set_cursor(initialized=False, value=0)

    def _set_cursor(self, *, initialized: bool, value: int):
        self.conn.execute(
            "update public.memory_rumination_cursors set initialized = %s, "
            "last_processed_message_id = %s, last_scheduled_date = null "
            "where assistant_id = %s",
            (initialized, value, ASSISTANT),
        )

    def _claim(self, first, last, *, trigger="rumination_manual", first_batch=False,
               scheduled_execution_id=None):
        claim = self._call("claim_rumination_batch", {
            "p_assistant_id": ASSISTANT,
            "p_trigger": trigger,
            "p_first_message_id": first,
            "p_last_message_id": last,
            "p_message_count": last - first + 1,
            "p_first_batch": first_batch,
            "p_scheduled_execution_id": scheduled_execution_id,
        })
        self.assertEqual(claim["status"], "claimed", claim)
        return claim["run_id"]

    def _commit(self, run_id, ops):
        return self._call("commit_rumination_batch", {
            "p_run_id": run_id,
            "p_ops": {"operations": ops},
        })

    def _cursor(self):
        return self._query_one(
            "select last_processed_message_id from public.memory_rumination_cursors "
            "where assistant_id = %s",
            (ASSISTANT,),
        )

    def _initialized(self):
        return self._query_one(
            "select initialized from public.memory_rumination_cursors "
            "where assistant_id = %s",
            (ASSISTANT,),
        )

    def _active_memory(self, where, params=None):
        return self._query_one(
            f"select id from public.memories where is_active and verified = 'verified' and {where}",
            params,
        )

    def _thread_snapshot(self, memory_id):
        """The exact snapshot the model read and must echo on thread ops."""
        row = self._query_row(
            "select memory_key, continuity_id::text, content_hash, thread_state "
            "from public.memories where id = %s",
            (memory_id,),
        )
        return {
            "target_memory_key": row[0],
            "target_continuity_id": row[1],
            "target_content_hash": row[2],
            "target_thread_state": row[3],
        }

