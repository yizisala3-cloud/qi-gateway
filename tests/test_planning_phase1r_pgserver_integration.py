    def test_after_completion_early_window_concurrent_connections(self):
        # BF3/G：真实 PostgreSQL 上两个不同 key 的并发提前完成——advisory
        # lock 把后到者的窗口检查串行化到先到事务提交之后，只允许一次有效
        # 完成推进。
        task_id = self._query(
            """
            insert into public.planning_task (
                content, task_type, time_mode, estimated_minutes, is_active,
                interval_days, refresh_mode, refresh_enabled,
                created_at, updated_at
            ) values (
                '间歇', 'interval', 'duration', 30, true,
                3, 'after_completion', true,
                '2026-10-07T06:00:00+08:00', '2026-10-07T06:00:00+08:00'
            ) returning id;
            """
        )[0][0]
        uri = self.server.get_uri()
        conn_a = psycopg.connect(uri)  # 请求 A：先到，未提交（持有 advisory lock）
        conn_b = psycopg.connect(uri)  # 请求 B：后到
        insert_sql = """
            insert into public.planning_occurrence (
                task_id, for_date, round_key, schedule_date, display_cycle_date,
                display_reason, status, closed_at, handled_at, sort_order,
                estimated_time_source, fixed_source, schedule_managed, source,
                early_period_date, generation_request_key,
                content_snapshot, display_content, time_mode_snapshot,
                created_at, updated_at
            ) values (
                %(task_id)s, '2026-10-14',
                'early:2026-10-14:' || %(key)s,
                '2026-10-14', '2026-10-14', 'initial', 'completed',
                %(handled)s, %(handled)s, 40,
                'unassigned', null, true, 'early', null, %(key)s,
                '间歇', '间歇', 'duration',
                %(handled)s, %(handled)s
            );
            """
        outcome = {}

        def request_b():
            try:
                conn_b.execute(insert_sql, {
                    "task_id": task_id, "key": "b" * 32,
                    "handled": "2026-10-14T08:00:00.5+08:00",
                })
                outcome["inserted"] = True
            except Exception as exc:  # noqa: BLE001 - 任意数据库层拒绝都算收敛
                outcome["error"] = exc

        try:
            conn_a.execute(insert_sql, {
                "task_id": task_id, "key": "a" * 32,
                "handled": "2026-10-14T08:00:00+08:00",
            })
            worker = threading.Thread(target=request_b)
            worker.start()
            time.sleep(1.0)
            self.assertTrue(worker.is_alive(),
                            "B must block on the advisory lock while A is uncommitted")
            conn_a.commit()  # A 的成功事实提交 → B 的检查看到它并拒绝
            worker.join(timeout=10)
            self.assertFalse(worker.is_alive())
            self.assertNotIn("inserted", outcome)
            self.assertIn(
                "after_completion early completions within the same 30-minute window",
                str(outcome.get("error")),
            )
            conn_b.rollback()
            count = self._query(
                "select count(*) from public.planning_occurrence "
                "where task_id = %(id)s and source = 'early'",
                {"id": task_id},
            )[0][0]
            self.assertEqual(count, 1)
        finally:
            conn_a.close()
            conn_b.close()

