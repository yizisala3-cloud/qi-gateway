def _split_top_level_statements(sql):
    """把迁移 SQL 拆成顶层语句序列（仅服务窗口迁移重放测试的最小实现）。

    逐字符扫描：跳过 ``--`` 行注释；单引号字符串（含 ``''`` 转义）与
    ``$tag$`` 美元引用块内部的分号不拆分——``DO $$ ... $$`` 等复合块保持
    完整；语句按文件真实顺序返回，显式 ``begin`` / ``commit`` 原样保留。
    逐条发送时原子性只能来自迁移文件自身的事务边界，而不是 Simple Query
    对整串语句提供的隐式事务。
    """
    statements = []
    buf = []
    i = 0
    n = len(sql)
    in_line_comment = False
    in_single_quote = False
    dollar_tag = None
    while i < n:
        ch = sql[i]
        if in_line_comment:
            if ch == "\n":
                in_line_comment = False
                buf.append(" ")
            i += 1
            continue
        if in_single_quote:
            buf.append(ch)
            if ch == "'":
                if sql.startswith("''", i):
                    buf.append("'")
                    i += 2
                    continue
                in_single_quote = False
            i += 1
            continue
        if dollar_tag is not None:
            if sql.startswith(dollar_tag, i):
                buf.append(dollar_tag)
                i += len(dollar_tag)
                dollar_tag = None
            else:
                buf.append(ch)
                i += 1
            continue
        if sql.startswith("--", i):
            in_line_comment = True
            i += 2
            continue
        if ch == "'":
            in_single_quote = True
            buf.append(ch)
            i += 1
            continue
        match = re.match(r"\$(\w*)\$", sql[i:])
        if match:
            dollar_tag = match.group(0)
            buf.append(dollar_tag)
            i += len(dollar_tag)
            continue
        if ch == ";":
            statement = "".join(buf).strip()
            if statement:
                statements.append(statement)
            buf = []
            i += 1
            continue
        buf.append(ch)
        i += 1
    tail = "".join(buf).strip()
    if tail:
        statements.append(tail)
    return statements
