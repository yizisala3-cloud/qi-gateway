    def test_f2_e2_dual_standdown_registrations_merge(self):
        # E2：两个 stand-down 并发登记不同 absorbed 键——后到者的原子合并
        # 在行锁下读取已提交的最新数组（READ COMMITTED 重评估），先登记的
        # 键不被覆盖；两个键都保留。
        source_occ = self._fresh_occurrence(
            round_key="cycle:2026-10-17", schedule_date="2026-10-17")
        task_id = self._reschedule_task(source_occ, "kA", state="completed")
        key1 = f"reschedule:{source_occ}:k1"
        key_b = f"reschedule:{source_occ}:kB"
        key_c = f"reschedule:{source_occ}:kC"
        self._query(
            "update public.planning_task set request_absorbed_keys = %(abs)s "
            "where id = %(id)s",
            {"abs": [key1], "id": task_id},
        )
        uri = self.server.get_uri()
        conn_b = psycopg.connect(uri)
        conn_c = psycopg.connect(uri)
        params_b = {"task_id": task_id, "key": key_b, "now": REPRO_NOW}
        params_c = {"task_id": task_id, "key": key_c, "now": REPRO_NOW}
        try:
            result_b = conn_b.execute(self._ABSORB_SQL, params_b).fetchone()
            assert result_b == (True,)  # B 登记成功，未提交（持有行锁）
            outcome = {}

            def register_c():
                try:
                    outcome["result"] = conn_c.execute(
                        self._ABSORB_SQL, params_c).fetchone()
                except Exception as exc:  # noqa: BLE001
                    outcome["error"] = exc

            worker = threading.Thread(target=register_c)
            worker.start()
            time.sleep(1.0)
            self.assertTrue(worker.is_alive(),
                            "C must block on the row lock while B is uncommitted")
            conn_b.commit()  # B 提交 → C 的合并读取到 [k1, kB]
            worker.join(timeout=10)
            self.assertFalse(worker.is_alive())
            self.assertEqual(outcome.get("result"), (True,))
            conn_c.commit()
            current, absorbed = self._task_identity(task_id)
            assert current.endswith(":kA")
            assert {key1, key_b, key_c} <= absorbed, "no key may vanish"
        finally:
            conn_b.close()
            conn_c.close()

