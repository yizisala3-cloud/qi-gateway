    def test_adopt_identity_cas_pattern_on_real_postgres(self):
        # C-1：双连接真 PostgreSQL 验证 adopt 身份 CAS 模式——基于过期读取
        # 的条件更新必然 0 行命中（丢更新被数据库拒绝）；失败方重读后以
        # 最新键 CAS 登记 absorbed，全部请求键保持可追踪。
        source_occ = self._fresh_occurrence(
            round_key="cycle:2026-10-16", schedule_date="2026-10-16")
        task_id = self._reschedule_task(source_occ, "k1", state="completed")
        self._query(
            "update public.planning_task set request_absorbed_keys = '{}' where id = %(id)s",
            {"id": task_id},
        )
        uri = self.server.get_uri()
        conn_a = psycopg.connect(uri, autocommit=True)
        conn_b = psycopg.connect(uri, autocommit=True)
        key1 = f"reschedule:{source_occ}:k1"
        key_a = f"reschedule:{source_occ}:kA"
        key_b = f"reschedule:{source_occ}:kB"
        try:
            select_sql = (
                "select request_key, request_absorbed_keys from public.planning_task "
                "where id = %(id)s"
            )
            row_a = conn_a.execute(select_sql, {"id": task_id}).fetchone()
            row_b = conn_b.execute(select_sql, {"id": task_id}).fetchone()
            assert row_a[0] == key1 and row_b[0] == key1  # 双方读到同一现状

            # B 先提交身份 CAS：赢得接管
            won_b = conn_b.execute(
                "update public.planning_task set request_key = %(new)s, "
                "request_absorbed_keys = %(abs)s "
                "where id = %(id)s and request_key = %(expected)s returning id",
                {"new": key_b, "abs": [key1], "id": task_id, "expected": key1},
            ).fetchall()
            assert len(won_b) == 1

            # A 基于过期读取提交同一条件的 CAS：必须 0 行命中
            lost_a = conn_a.execute(
                "update public.planning_task set request_key = %(new)s, "
                "request_absorbed_keys = %(abs)s "
                "where id = %(id)s and request_key = %(expected)s returning id",
                {"new": key_a, "abs": [key1], "id": task_id, "expected": key1},
            ).fetchall()
            assert lost_a == [], "stale CAS must not overwrite the newer identity"

            # A 重读最新状态 → stand-down：以最新键为条件的 absorbed 登记
            fresh = conn_a.execute(select_sql, {"id": task_id}).fetchone()
            assert fresh[0] == key_b
            absorbed = list(fresh[1] or []) + [key_a]
            registered = conn_a.execute(
                "update public.planning_task set request_absorbed_keys = %(abs)s "
                "where id = %(id)s and request_key = %(expected)s returning id",
                {"abs": absorbed, "id": task_id, "expected": fresh[0]},
            ).fetchall()
            assert len(registered) == 1

            final = conn_a.execute(select_sql, {"id": task_id}).fetchone()
            assert final[0] == key_b
            assert set(final[1] or []) >= {key1, key_a}, "no key may vanish"
        finally:
            conn_a.close()
            conn_b.close()

