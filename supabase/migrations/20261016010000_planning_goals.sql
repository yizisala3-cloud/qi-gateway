-- Long-term goals. Additive: existing round identities/lifecycle writers stay intact.
-- No historical contributions are backfilled. The baseline only remembers rounds
-- already complete so that corrections/rebinding cannot turn them into new work.
begin;

create table if not exists public.planning_goal (
    id bigint generated by default as identity primary key,
    content text not null check (length(btrim(content)) > 0),
    target_value numeric not null check (target_value > 0 and target_value::text not in ('NaN','Infinity','-Infinity')),
    unit text not null check (length(btrim(unit)) > 0),
    planned_count bigint not null check (planned_count between 1 and 9007199254740991),
    manual_adjustment bigint not null default 0,
    version bigint not null default 1,
    created_at timestamptz not null default clock_timestamp(),
    updated_at timestamptz not null default clock_timestamp()
);

create table if not exists public.planning_goal_link (
    id bigint generated by default as identity primary key,
    goal_id bigint not null references public.planning_goal(id) on delete cascade,
    -- Deliberately no task FK: deletion must not erase provenance or lock a task
    -- from the occurrence -> goal trigger path (existing task writers lock first).
    task_id bigint not null,
    task_content text not null,
    task_type text not null,
    linked_at timestamptz not null default clock_timestamp(),
    ended_at timestamptz,
    end_reason text
);
create unique index if not exists planning_goal_link_current_goal_uq
    on public.planning_goal_link(goal_id) where ended_at is null;
create unique index if not exists planning_goal_link_current_task_uq
    on public.planning_goal_link(task_id) where ended_at is null;

create table if not exists public.planning_goal_round_fact (
    task_id bigint not null,
    round_key text not null,
    source_ids bigint[] not null,
    is_completed boolean not null,
    ever_completed boolean not null,
    first_completed_at timestamptz,
    primary key (task_id, round_key)
);
create table if not exists public.planning_goal_contribution (
    goal_id bigint not null references public.planning_goal(id) on delete cascade,
    task_id bigint not null,
    round_key text not null,
    link_id bigint not null references public.planning_goal_link(id) on delete cascade,
    source_ids bigint[] not null,
    active boolean not null default true,
    recorded_at timestamptz not null default clock_timestamp(),
    primary key (goal_id, task_id, round_key)
);
create table if not exists public.planning_goal_operation (
    request_key uuid primary key,
    intent jsonb not null,
    result jsonb not null,
    created_at timestamptz not null default clock_timestamp()
);
create index if not exists planning_goal_contribution_source_idx
    on public.planning_goal_contribution(task_id, round_key);
create index if not exists planning_goal_link_history_idx on public.planning_goal_link(goal_id, id);

-- A complete ordinary round has exactly one ordinary row; a hollow round has
-- exactly its two completed phases. Current task rules never reinterpret it.
insert into public.planning_goal_round_fact
    (task_id, round_key, source_ids, is_completed, ever_completed, first_completed_at)
select task_id, round_key, array_agg(id order by id),
       bool_and(status = 'completed') and
           ((count(*) = 1 and count(phase) = 0) or
            (count(*) = 2 and count(*) filter (where phase = 'start') = 1
                         and count(*) filter (where phase = 'end') = 1)),
       bool_and(status = 'completed') and
           ((count(*) = 1 and count(phase) = 0) or
            (count(*) = 2 and count(*) filter (where phase = 'start') = 1
                         and count(*) filter (where phase = 'end') = 1)),
       case when bool_and(status = 'completed') then clock_timestamp() end
from public.planning_occurrence where round_key is not null
group by task_id, round_key on conflict (task_id, round_key) do nothing;

create or replace function public.planning_goal_lock() returns void
language plpgsql volatile set search_path = pg_catalog, public as $$
begin
    -- Commands/triggers use fresh SPI snapshots after the lock. Fail explicitly
    -- instead of silently using an old snapshot under a non-default isolation.
    if current_setting('transaction_isolation') <> 'read committed' then
        raise exception using errcode = 'PG400', message = '目标操作需要 read committed 事务';
    end if;
    perform pg_advisory_xact_lock(716, 20261016);
end $$;

create or replace function public.planning_goal_sync_round() returns trigger
language plpgsql security definer set search_path = pg_catalog, public as $$
declare
    complete_now boolean;
    completed_before boolean;
    sources bigint[];
    binding public.planning_goal_link%rowtype;
begin
    if new.round_key is null then return null; end if;
    if tg_op = 'UPDATE' and old.status is not distinct from new.status then return null; end if;
    perform public.planning_goal_lock();
    select array_agg(id order by id), bool_and(status = 'completed') and
        ((count(*) = 1 and count(phase) = 0) or
         (count(*) = 2 and count(*) filter (where phase = 'start') = 1
                      and count(*) filter (where phase = 'end') = 1))
    into sources, complete_now from public.planning_occurrence
    where task_id = new.task_id and round_key = new.round_key;
    select ever_completed into completed_before from public.planning_goal_round_fact
    where task_id = new.task_id and round_key = new.round_key;
    insert into public.planning_goal_round_fact
        (task_id, round_key, source_ids, is_completed, ever_completed, first_completed_at)
    values (new.task_id, new.round_key, sources, complete_now, complete_now,
            case when complete_now then clock_timestamp() end)
    on conflict (task_id, round_key) do update set
        source_ids = excluded.source_ids, is_completed = excluded.is_completed,
        ever_completed = planning_goal_round_fact.ever_completed or excluded.ever_completed,
        first_completed_at = coalesce(planning_goal_round_fact.first_completed_at, excluded.first_completed_at);
    if complete_now and not coalesce(completed_before, false) then
        select * into binding from public.planning_goal_link
        where task_id = new.task_id and ended_at is null;
        if found then
            insert into public.planning_goal_contribution
                (goal_id, task_id, round_key, link_id, source_ids)
            values (binding.goal_id, new.task_id, new.round_key, binding.id, sources)
            on conflict (goal_id, task_id, round_key) do nothing;
        end if;
    end if;
    -- Corrections continue to adjust their original source after unlink/deletion.
    -- Re-completion restores that same contribution; it never creates a second.
    update public.planning_goal_contribution set active = complete_now
    where task_id = new.task_id and round_key = new.round_key
      and active is distinct from complete_now;
    return null;
end $$;
drop trigger if exists planning_goal_occurrence_sync on public.planning_occurrence;
create trigger planning_goal_occurrence_sync
after insert or update of status on public.planning_occurrence
for each row execute function public.planning_goal_sync_round();

create or replace function public.planning_goal_task_deleted() returns trigger
language plpgsql security definer set search_path = pg_catalog, public as $$
begin
    if tg_op = 'UPDATE' and (new.deleted_at is null or old.deleted_at is not null) then return null; end if;
    perform public.planning_goal_lock();
    with ended as (
        update public.planning_goal_link set ended_at = clock_timestamp(), end_reason = 'task_deleted'
        where task_id = old.id and ended_at is null returning goal_id
    )
    update public.planning_goal set version = version + 1, updated_at = clock_timestamp()
    where id in (select goal_id from ended);
    return null;
end $$;
drop trigger if exists planning_goal_task_delete_sync on public.planning_task;
create trigger planning_goal_task_delete_sync
after delete or update of deleted_at on public.planning_task
for each row execute function public.planning_goal_task_deleted();

create or replace function public.planning_goal_read(p_goal_id bigint default null) returns jsonb
language sql stable security definer set search_path = pg_catalog, public as $$
    select case when p_goal_id is null then coalesce(jsonb_agg(item order by id desc), '[]'::jsonb)
                else (jsonb_agg(item))->0 end
    from (
        select g.id, to_jsonb(g) || jsonb_build_object(
            'target_value', g.target_value::text,
            'automatic_count', counts.n,
            'executed_count', greatest(0, counts.n + g.manual_adjustment),
            'percentage', round(greatest(0, counts.n + g.manual_adjustment)::numeric * 100 / g.planned_count, 2),
            'achieved', greatest(0, counts.n + g.manual_adjustment) >= g.planned_count,
            'current_link', (
                select to_jsonb(l) || jsonb_build_object(
                    'task_content', coalesce(t.content, l.task_content),
                    'refresh_enabled', t.refresh_enabled)
                from public.planning_goal_link l left join public.planning_task t on t.id = l.task_id
                where l.goal_id = g.id and l.ended_at is null),
            'history', coalesce((select jsonb_agg(to_jsonb(l) order by l.id desc)
                from public.planning_goal_link l where l.goal_id = g.id and l.ended_at is not null), '[]'::jsonb)
        ) as item
        from public.planning_goal g
        cross join lateral (select count(*) as n from public.planning_goal_contribution c
                            where c.goal_id = g.id and c.active) counts
        where p_goal_id is null or g.id = p_goal_id
    ) summaries
$$;

create or replace function public.planning_goal_candidates() returns jsonb
language sql stable security definer set search_path = pg_catalog, public as $$
    select coalesce(jsonb_agg(jsonb_build_object(
        'id', t.id, 'content', t.content, 'task_type', t.task_type,
        'refresh_enabled', t.refresh_enabled, 'goal_id', l.goal_id) order by t.id desc), '[]'::jsonb)
    from public.planning_task t left join public.planning_goal_link l
      on l.task_id = t.id and l.ended_at is null
    where t.is_active and t.deleted_at is null and t.task_type in ('daily','interval','weekly','monthly')
$$;

create or replace function public.planning_goal_command(
    p_action text, p_goal_id bigint, p_payload jsonb, p_request_key uuid
) returns jsonb language plpgsql security definer set search_path = pg_catalog, public as $$
declare
    intent_value jsonb := jsonb_build_object('action', p_action, 'goal_id', p_goal_id, 'payload', p_payload);
    previous public.planning_goal_operation%rowtype;
    goal public.planning_goal%rowtype;
    task public.planning_task%rowtype;
    value_number numeric;
    total_count bigint;
    target_task bigint;
    result_value jsonb;
begin
    perform public.planning_goal_lock();
    if p_request_key is null or jsonb_typeof(p_payload) is distinct from 'object'
       or p_action is null or p_action not in ('create','edit','link','adjust','delete') then
        raise exception using errcode = 'PG400', message = '目标请求参数无效';
    end if;
    select * into previous from public.planning_goal_operation where request_key = p_request_key;
    if found then
        if previous.intent <> intent_value then
            raise exception using errcode = 'PG409', message = '操作身份已用于其它内容，请先核实原操作';
        end if;
        return previous.result;
    end if;
    if p_action <> 'create' then
        select * into goal from public.planning_goal where id = p_goal_id;
        if not found then raise exception using errcode = 'PG404', message = '目标已删除或不存在'; end if;
        if jsonb_typeof(p_payload->'expected_version') is distinct from 'number'
           or p_payload->>'expected_version' !~ '^[0-9]+$'
           or (p_payload->>'expected_version')::numeric <> goal.version then
            raise exception using errcode = 'PG409', message = '目标已被其它操作修改，请重新读取后再提交';
        end if;
    end if;
    if p_action in ('create','edit') then
        if jsonb_typeof(p_payload->'content') is distinct from 'string'
           or nullif(btrim(p_payload->>'content'), '') is null
           or jsonb_typeof(p_payload->'unit') is distinct from 'string'
           or nullif(btrim(p_payload->>'unit'), '') is null
           or jsonb_typeof(p_payload->'target_value') not in ('string','number')
           or p_payload->>'target_value' is null then
            raise exception using errcode = 'PG400', message = '请填写目标内容、正数数值和单位';
        end if;
        begin
            value_number := (p_payload->>'target_value')::numeric;
        exception when invalid_text_representation or numeric_value_out_of_range then
            raise exception using errcode = 'PG400', message = '目标数值必须为正数';
        end;
        if value_number <= 0 or value_number::text in ('NaN','Infinity','-Infinity') then
            raise exception using errcode = 'PG400', message = '目标数值必须为有限正数';
        end if;
        if jsonb_typeof(p_payload->'planned_count') is distinct from 'number'
           or p_payload->>'planned_count' !~ '^[0-9]+$'
           or (p_payload->>'planned_count')::numeric not between 1 and 9007199254740991 then
            raise exception using errcode = 'PG400', message = '计划执行次数须为正整数';
        end if;
        if p_action = 'create' then
            insert into public.planning_goal(content, target_value, unit, planned_count)
            values (btrim(p_payload->>'content'), value_number, btrim(p_payload->>'unit'),
                    (p_payload->>'planned_count')::bigint) returning * into goal;
        else
            update public.planning_goal set content = btrim(p_payload->>'content'),
                target_value = value_number, unit = btrim(p_payload->>'unit'),
                planned_count = (p_payload->>'planned_count')::bigint,
                version = version + 1, updated_at = clock_timestamp()
            where id = goal.id;
        end if;
    elsif p_action = 'adjust' then
        if jsonb_typeof(p_payload->'executed_count') is distinct from 'number'
           or p_payload->>'executed_count' !~ '^[0-9]+$'
           or (p_payload->>'executed_count')::numeric not between 0 and 9007199254740991 then
            raise exception using errcode = 'PG400', message = '已执行次数须为非负整数';
        end if;
        select count(*) into total_count from public.planning_goal_contribution where goal_id = goal.id and active;
        update public.planning_goal set manual_adjustment = (p_payload->>'executed_count')::bigint - total_count,
            version = version + 1, updated_at = clock_timestamp() where id = goal.id;
    elsif p_action = 'link' then
        if not (p_payload ? 'task_id') then
            raise exception using errcode = 'PG400', message = '请选择待办或明确解除关联';
        end if;
        if p_payload->'task_id' <> 'null'::jsonb then
            if jsonb_typeof(p_payload->'task_id') is distinct from 'number'
               or p_payload->>'task_id' !~ '^[0-9]+$'
               or (p_payload->>'task_id')::numeric not between 1 and 9007199254740991 then
                raise exception using errcode = 'PG400', message = '待办身份无效';
            end if;
            target_task := (p_payload->>'task_id')::bigint;
            -- Plain MVCC reads only. Never acquire task/occurrence row locks
            -- while holding the goal lock: existing writers lock those first.
            select * into task from public.planning_task where id = target_task;
            if not found or not task.is_active or task.deleted_at is not null
               or task.task_type not in ('daily','interval','weekly','monthly') then
                raise exception using errcode = 'PG400', message = '仅可关联有效的重复待办';
            end if;
            if exists(select 1 from public.planning_goal_link where task_id = target_task
                      and ended_at is null and goal_id <> goal.id) then
                raise exception using errcode = 'PG409', message = '该待办已关联其它目标，请先解除原关联';
            end if;
        end if;
        if not exists(select 1 from public.planning_goal_link where goal_id = goal.id
                      and task_id = target_task and ended_at is null) then
            update public.planning_goal_link set ended_at = clock_timestamp(), end_reason = 'unlinked'
            where goal_id = goal.id and ended_at is null;
            if target_task is not null then
                insert into public.planning_goal_link(goal_id, task_id, task_content, task_type)
                values (goal.id, task.id, task.content, task.task_type);
            end if;
            update public.planning_goal set version = version + 1, updated_at = clock_timestamp() where id = goal.id;
        end if;
    else
        delete from public.planning_goal where id = goal.id;
    end if;
    result_value := case when p_action = 'delete' then jsonb_build_object('id', goal.id, 'deleted', true)
                         else public.planning_goal_read(goal.id) end;
    insert into public.planning_goal_operation(request_key, intent, result) values (p_request_key, intent_value, result_value);
    return result_value;
end $$;

