-- Chat recall: best-effort cooldown plus actual injection snapshots.
-- Apply after the existing migration history. No chat_messages writes.
begin;

create table if not exists public.memory_recall_history (
    id bigint generated by default as identity primary key,
    batch_id uuid not null,
    memory_id integer not null,
    recalled_at timestamptz not null,
    position smallint not null check (position between 1 and 20),
    title text not null default '',
    continuity_type text,
    injection_text text not null check (char_length(injection_text) between 1 and 2400),
    unique (batch_id, memory_id)
);
-- Deliberately no memory FK: deleting/undoing a memory must preserve snapshots.
create index if not exists memory_recall_history_time_idx
    on public.memory_recall_history (recalled_at desc, batch_id desc, position asc, id desc);

-- Small receipts, separate from the 150 display events, protect retries after
-- history pruning. Receipts live 48h; batches older than 24h cannot be replayed.
create table if not exists public.memory_recall_batches (
    batch_id uuid primary key,
    created_at timestamptz not null default clock_timestamp()
);
create index if not exists memory_recall_batches_created_idx
    on public.memory_recall_batches (created_at);
alter table public.memory_recall_history enable row level security;
alter table public.memory_recall_batches enable row level security;
revoke all on public.memory_recall_history, public.memory_recall_batches
    from public, anon, authenticated, service_role;
grant select on public.memory_recall_history to service_role;

create or replace function public.record_memory_recall_batch_v1(
    p_batch_id uuid, p_recalled_at timestamptz, p_memories jsonb
)
returns jsonb
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
    v_count integer;
    v_claimed integer;
    v_item jsonb;
begin
    if p_batch_id is null or p_recalled_at is null or not isfinite(p_recalled_at)
       or p_recalled_at < statement_timestamp() - interval '24 hours'
       or p_recalled_at > statement_timestamp() + interval '5 minutes' then
        raise exception 'invalid_memory_recall_batch_time';
    end if;
    if p_memories is null or jsonb_typeof(p_memories) <> 'array' then
        raise exception 'invalid_memory_recall_batch';
    end if;
    v_count := jsonb_array_length(p_memories);
    if v_count not between 1 and 20 then
        raise exception 'invalid_memory_recall_batch_size';
    end if;
    if exists (
        select 1 from jsonb_array_elements(p_memories) item
        where jsonb_typeof(item) <> 'object'
           or jsonb_typeof(item->'memory_id') is distinct from 'number'
           or (item->>'memory_id') !~ '^[1-9][0-9]*$'
           or jsonb_typeof(item->'injection_text') is distinct from 'string'
           or char_length(btrim(item->>'injection_text')) not between 1 and 2400
    ) or (select count(distinct (item->>'memory_id')::integer)
          from jsonb_array_elements(p_memories) item) <> v_count
       or (select sum(char_length(item->>'injection_text'))
           from jsonb_array_elements(p_memories) item) > 2400 then
        raise exception 'invalid_memory_recall_item';
    end if;

    -- Only background writers take this lock. Search never locks or waits here.
    perform pg_advisory_xact_lock(hashtextextended('memory_recall_history_retention', 0));
    insert into public.memory_recall_batches (batch_id) values (p_batch_id)
        on conflict do nothing;
    get diagnostics v_claimed = row_count;
    if v_claimed = 0 then
        return jsonb_build_object('status', 'already_recorded', 'inserted_count', 0);
    end if;

    insert into public.memory_recall_history
        (batch_id, memory_id, recalled_at, position, title, continuity_type, injection_text)
    select p_batch_id, (item->>'memory_id')::integer, p_recalled_at, ordinal::smallint,
           coalesce(item->>'title', ''), item->>'continuity_type', item->>'injection_text'
    from jsonb_array_elements(p_memories) with ordinality as input(item, ordinal);

    -- Consistent memory lock order, and no duplicate heat on batch retries.
    for v_item in select item from jsonb_array_elements(p_memories) item
                  order by (item->>'memory_id')::integer loop
        update public.memories
        set heat = least(100.0, least(greatest(coalesce(heat, 0), 0), 100)
                    + 8 * (1.0 - least(greatest(coalesce(heat, 0), 0), 100) / 100.0)),
            recall_count = coalesce(recall_count, 0) + 1,
            last_recalled_at = greatest(last_recalled_at, p_recalled_at)
        where id = (v_item->>'memory_id')::integer
          and is_active = true and verified = 'verified';
    end loop;

    delete from public.memory_recall_history where id in (
        select id from public.memory_recall_history
        order by recalled_at desc, batch_id desc, position asc, id desc offset 150
    );
    delete from public.memory_recall_batches
        where created_at < statement_timestamp() - interval '48 hours';
    return jsonb_build_object('status', 'recorded', 'inserted_count', v_count);
end;
$function$;
revoke all on function public.record_memory_recall_batch_v1(uuid, timestamptz, jsonb)
    from public, anon, authenticated;
grant execute on function public.record_memory_recall_batch_v1(uuid, timestamptz, jsonb)
    to service_role;

